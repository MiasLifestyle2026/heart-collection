(() => {
  "use strict";

  const $ = id => document.getElementById(id);

  function getLanguage() {
    const code = $("lang")?.value || "de";
    return HEART_UI[code] ? code : "en";
  }

  function setText(id, value) {
    const element = $(id);
    if (element && element.textContent !== value) {
      element.textContent = value;
    }
  }

  function updateInterface() {
    const code = getLanguage();
    const x = HEART_UI[code];

    document.documentElement.lang = code;

    const heading = $("heading");
    if (heading) {
      const desired = `${x.heading}<br><em>${x.heading2}</em>`;
      if (heading.innerHTML !== desired) {
        heading.innerHTML = desired;
      }
    }

    const labels = {
      subtitle: x.subtitle,
      categoryLabel: x.category,
      shuffleLabel: x.shuffle,
      prevText: x.prev,
      nextText: x.next,
      shareText: x.share,
      tap: x.tap,
      footerText: x.footer,
      soloText: x.solo,
      coupleText: x.couple,
      createRoom: x.create,
      joinRoom: x.join,
      leaveRoom: x.leave,
      copyRoom: x.copy,
      roomLabel: x.room
    };

    Object.entries(labels).forEach(([id, value]) => {
      setText(id, value);
    });

    const categorySelect = $("category");
    if (categorySelect) {
      Array.from(categorySelect.options).forEach((option, i) => {
        if (x.categories[i] &&
            option.textContent !== x.categories[i]) {
          option.textContent = x.categories[i];
        }
      });
    }

    const number = Number($("number")?.textContent);
    const cards = window.HEART_CARDS;

    if (Array.isArray(cards)) {
      const card = cards.find(c => Number(c.id) === number);
      if (card) {
        const categoryName = x.categories[Number(card.cat) + 1];
        if (categoryName) {
          setText("categoryName", categoryName.toUpperCase());
        }
      }
    }

    const favoriteText = $("favoriteText");
    if (favoriteText) {
      const isSaved = $("favorite")?.firstChild
        ?.textContent?.includes("♥");
      setText("favoriteText", isSaved ? x.saved : x.favorite);
    }

    const front = document.querySelector(
      ".playing-card .front .big"
    );

    if (front) {
      const desired =
        `100<br><em>${x.front}</em><br>${x.front2}`;

      if (front.innerHTML !== desired) {
        front.innerHTML = desired;
      }

      front.dir = ["ar", "ur"].includes(code) ? "rtl" : "auto";
    }

    const joinInput = $("joinInput");
    if (joinInput) {
      const placeholders = {
        de: "Einladungslink oder Raumcode",
        en: "Invitation link or room code",
        es: "Enlace de invitación o código",
        fr: "Lien d'invitation ou code",
        zh: "邀请链接或房间代码",
        ur: "دعوتی لنک یا کمرے کا کوڈ",
        hi: "निमंत्रण लिंक या रूम कोड",
        ar: "رابط الدعوة أو رمز الغرفة"
      };

      joinInput.placeholder = placeholders[code];
    }
  }

  const languageSelect = $("lang");

  if (languageSelect) {
    languageSelect.addEventListener("change", () => {
      updateInterface();
    });
  }

  const watchedIds = [
    "heading",
    "categoryName",
    "favoriteText"
  ];

  watchedIds.forEach(id => {
    const element = $(id);
    if (!element) return;

    const observer = new MutationObserver(() => {
      updateInterface();
    });

    observer.observe(element, {
      childList: true,
      characterData: true,
      subtree: true
    });
  });

  updateInterface();
})();
                              
